import { NextResponse } from "next/server";
import type { NextRequest } from "next/server";
import { z, ZodError } from "zod";
import { db } from "@/lib/db";
import { requireUser } from "@/lib/auth";
import { writeAuditEvent } from "@/lib/audit";
import { canEditSiteTracker } from "@/lib/permissions";
import { validateEvidenceUpload } from "@/lib/tracker-evidence-rules";
import { verifyEvidenceObject } from "@/lib/tracker-storage";

const ConfirmSchema = z.object({
  siteId: z.string().min(1),
  stepId: z.string().min(1),
  storageKey: z.string().min(1),
  fileName: z.string().min(1),
  mimeType: z.string().min(1),
  size: z.number().int().positive(),
});

/** site-tracker-plan.md section 5, step 3: HEAD-verify the object actually landed and matches, then create the TrackerEvidence row (lazily creating TrackerSiteStep too — section 3's "no row = NOT_STARTED" still holds for status, this just gives the evidence somewhere to attach). */
export async function POST(request: NextRequest) {
  const user = await requireUser();
  if (!canEditSiteTracker(user)) {
    return NextResponse.json({ error: "You don't have permission to edit Site Tracker." }, { status: 403 });
  }

  let input: z.infer<typeof ConfirmSchema>;
  try {
    input = ConfirmSchema.parse(await request.json());
  } catch (err) {
    if (err instanceof ZodError) {
      return NextResponse.json({ error: "Invalid request body.", issues: err.issues }, { status: 400 });
    }
    return NextResponse.json({ error: "Invalid JSON body." }, { status: 400 });
  }

  // The key is server-generated by /presign in this exact shape — a
  // mismatch here means the client is trying to attach someone else's
  // upload to this site/step.
  const expectedPrefix = `site-tracker/${input.siteId}/${input.stepId}/`;
  if (!input.storageKey.startsWith(expectedPrefix)) {
    return NextResponse.json({ error: "storageKey does not match this site/step." }, { status: 400 });
  }

  const validation = validateEvidenceUpload({ mimeType: input.mimeType, sizeBytes: input.size });
  if (!validation.ok) {
    return NextResponse.json({ error: validation.error }, { status: 400 });
  }

  const [site, step] = await Promise.all([
    db.site.findUnique({ where: { id: input.siteId } }),
    db.trackerStep.findUnique({ where: { id: input.stepId } }),
  ]);
  if (!site || !site.usedInTracker) {
    return NextResponse.json({ error: "Site not found." }, { status: 404 });
  }
  if (!step || !step.isActive) {
    return NextResponse.json({ error: "Step not found." }, { status: 404 });
  }

  const verified = await verifyEvidenceObject({ key: input.storageKey, expectedSize: input.size });
  if (!verified) {
    return NextResponse.json(
      { error: "Could not verify the upload — the file may not have finished uploading. Try again." },
      { status: 400 }
    );
  }

  const result = await db.$transaction(async (tx) => {
    const siteStep = await tx.trackerSiteStep.upsert({
      where: { siteId_stepId: { siteId: input.siteId, stepId: input.stepId } },
      update: {},
      create: { siteId: input.siteId, stepId: input.stepId },
    });

    const evidence = await tx.trackerEvidence.create({
      data: {
        siteStepId: siteStep.id,
        storageKey: input.storageKey,
        fileName: input.fileName,
        mimeType: input.mimeType,
        sizeBytes: input.size,
        kind: validation.kind,
        uploadedById: user.id,
      },
    });

    const evidenceCount = await tx.trackerEvidence.count({ where: { siteStepId: siteStep.id } });

    await writeAuditEvent(tx, {
      actor: user,
      entityType: "TrackerEvidence",
      entityId: evidence.id,
      action: "CREATE",
      newValue: { fileName: input.fileName, mimeType: input.mimeType, sizeBytes: input.size },
      reference: `"${step.code} ${step.name}" on "${site.name}"`,
    });

    return { evidence, evidenceCount };
  });

  return NextResponse.json({
    evidence: {
      id: result.evidence.id,
      fileName: result.evidence.fileName,
      mimeType: result.evidence.mimeType,
      sizeBytes: result.evidence.sizeBytes,
      kind: result.evidence.kind,
      createdAt: result.evidence.createdAt,
    },
    evidenceCount: result.evidenceCount,
  });
}
